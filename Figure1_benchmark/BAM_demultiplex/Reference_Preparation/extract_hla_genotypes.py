import os
import sys
import subprocess
import argparse
import shutil
import glob
import json
import pandas as pd
import re

def check_dependency(tool_name):
    """Check if the tool exists in the PATH."""
    if not shutil.which(tool_name):
        print(f"Error: Tool '{tool_name}' not found. Please ensure it is installed and added to PATH.")
        sys.exit(1)

def run_command(cmd, desc=None):
    """Execute a Shell command."""
    if desc:
        print(f"--- {desc} ---")
    print(f"Run: {cmd}")
    try:
        subprocess.run(cmd, shell=True, check=True, executable='/bin/bash')
    except subprocess.CalledProcessError as e:
        print(f"Error executing command: {cmd}")
        raise e

def format_hla_allele(allele_str):
    """
    Format HLA alleles to 2-field precision (4-digit).
    Example: A*01:01:01:01 -> A*01:01
    """
    if not allele_str:
        return "NA"
    parts = allele_str.split(':')
    if len(parts) >= 2:
        return f"{parts[0]}:{parts[1]}"
    return allele_str

def process_single_bam_for_hla(bam_file, sample_name, out_dir, arcas_path, threads, genes):
    """
    Process a single BAM file: Extract Chr6 -> Sort -> BAM2Fastq -> ArcasHLA
    """
    sample_out_dir = os.path.join(out_dir, sample_name)
    os.makedirs(sample_out_dir, exist_ok=True)

    # 1. Extract Chr6 (accelerate subsequent processing)
    hla_bam = os.path.join(sample_out_dir, "hla_chr6.bam")
    
    if not os.path.exists(hla_bam):
        # Check for index; create if missing
        if not (os.path.exists(bam_file + '.bai') or os.path.exists(bam_file + '.csi')):
            run_command(f"samtools index -@ {min(4, threads)} '{bam_file}'", f"Indexing {sample_name}")
            
        run_command(f"samtools view -@ {threads} -b '{bam_file}' chr6 > '{hla_bam}'", f"Extracting Chr6 for {sample_name}")
        run_command(f"samtools index -@ {threads} '{hla_bam}'")
    
    # 2. Name Sort (required by CellRanger bamtofastq)
    sorted_bam = os.path.join(sample_out_dir, "name_sorted.bam")
    if not os.path.exists(sorted_bam):
        run_command(f"samtools sort -@ {threads} -n '{hla_bam}' -o '{sorted_bam}'", f"Name sorting for {sample_name}")

    # 3. BAM to FASTQ
    fastq_dir = os.path.join(sample_out_dir, "fastq")
    if not os.path.exists(fastq_dir) or not os.listdir(fastq_dir):
        run_command(f"cellranger bamtofastq '{sorted_bam}' '{fastq_dir}'", f"Bam2Fastq for {sample_name}")

    # 4. Find R2 Fastq (cDNA reads)
    fastq_files = glob.glob(os.path.join(fastq_dir, "**", "*_R2_*.fastq.gz"), recursive=True)
    
    if not fastq_files:
        print(f"Warning: No R2 FASTQ found for {sample_name}. Skipping genotyping.")
        return

    fastq_input = " ".join(fastq_files)
    
    # 5. Run arcasHLA Genotype
    # Check if results exist
    if os.path.exists(os.path.join(sample_out_dir, f"{sample_name}.genotype.json")):
         print(f"Genotyping result exists for {sample_name}, skipping.")
    else:
        # ArcasHLA generates sample_name.genotype.json in the output directory by default (if fastq naming is standard)
        # Note: FASTQ filenames might be long; the JSON filename generated by arcasHLA depends on the input FASTQ prefix.
        # We only specify the output directory.
        cmd_arcas = (
            f"{arcas_path} genotype "
            f"-t {threads} -v "
            f"--single {fastq_input} "
            f"-g {genes} "
            f"-o '{sample_out_dir}'"
        )
        run_command(cmd_arcas, f"Running arcasHLA for {sample_name}")

def aggregate_results(root_dir, genes, output_csv):
    """
    Recursively find all genotype.json files in the directory and merge them into a CSV.
    """
    print(f"\n--- Aggregating results into {output_csv} ---")
    
    # Recursive search
    json_files = glob.glob(os.path.join(root_dir, "**", "*.genotype.json"), recursive=True)
    
    if not json_files:
        print("Warning: No JSON result files found.")
        return

    data_dict = {}

    for jf in json_files:
        # Infer sample name: prioritize using the parent directory name
        # Directory structure is usually: outdir/SampleName/SampleName.genotype.json
        parent_dir = os.path.basename(os.path.dirname(jf))
        sample_name = parent_dir
        
        try:
            with open(jf, 'r') as f:
                data = json.load(f)
            
            sample_data = {}
            for gene in genes:
                alleles = data.get(gene, [])
                a1 = format_hla_allele(alleles[0]) if len(alleles) > 0 else "NA"
                a2 = format_hla_allele(alleles[1]) if len(alleles) > 1 else "NA"
                
                sample_data[f"{gene}1"] = a1
                sample_data[f"{gene}2"] = a2
            
            data_dict[sample_name] = sample_data
            
        except Exception as e:
            print(f"Error parsing {jf}: {e}")

    if not data_dict:
        print("No valid data extracted.")
        return

    # Convert to DataFrame and transpose (Samples as Columns)
    df = pd.DataFrame.from_dict(data_dict, orient='columns')

    # Column sorting (SampleID natural sorting)
    def natural_keys(text):
        return [int(c) if c.isdigit() else c for c in re.split(r'(\d+)', text)]
    
    sorted_cols = sorted(df.columns, key=natural_keys)
    df = df[sorted_cols]

    # Row sorting (Gene1, Gene2...)
    expected_index = []
    for gene in genes:
        expected_index.append(f"{gene}1")
        expected_index.append(f"{gene}2")
    
    df = df.reindex(expected_index)

    # Save
    df.to_csv(output_csv, index=True)
    print(f"Success! Transposed genotype table saved to: {output_csv}")

def main():
    parser = argparse.ArgumentParser(description="Extract and genotype HLA from BAM files (supports batch mode or split mode).")
    
    # Mutually exclusive group: Batch input vs. Single split
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("-i", "--inputs", nargs='+', help="Batch mode: Input multiple BAM file paths (e.g., /path/*/possorted.bam)")
    group.add_argument("-b", "--bam", help="Split mode: Input a single mixed BAM file (requires -c)")
    
    parser.add_argument("-c", "--barcodes", help="Barcode group file (only for -b split mode, sinto format)")
    parser.add_argument("-o", "--outdir", required=True, help="Root output directory for results")
    parser.add_argument("--arcas", required=True, help="Full path to the arcasHLA executable")
    
    # Optional arguments
    parser.add_argument("-t", "--threads", type=int, default=20, help="Number of threads (default: 20)")
    parser.add_argument("-g", "--genes", default="A,B,C,DPB1,DQB1,DRB1", help="HLA genes to genotype (comma-separated)")

    args = parser.parse_args()

    # Dependency check
    check_dependency("samtools")
    check_dependency("cellranger")
    check_dependency("sinto")
    
    if not os.path.exists(args.arcas):
        print(f"Error: arcasHLA path not found: {args.arcas}")
        sys.exit(1)

    gene_list = args.genes.split(',')
    os.makedirs(args.outdir, exist_ok=True)

    # --- Mode A: Batch Processing multiple BAMs ---
    if args.inputs:
        print(f"Mode: Batch Processing {len(args.inputs)} BAM files.")
        
        for bam_path in args.inputs:
            # Automatically infer sample name
            # Assumed path structure: /.../SampleID/possorted_genome_bam.bam
            parent_dir = os.path.basename(os.path.dirname(bam_path))
            filename = os.path.basename(bam_path)
            
            if filename == "possorted_genome_bam.bam":
                sample_name = parent_dir
            else:
                sample_name = filename.replace(".bam", "")
            
            print(f"\n>>> Processing Sample: {sample_name} <<<")
            try:
                process_single_bam_for_hla(bam_path, sample_name, args.outdir, args.arcas, args.threads, args.genes)
            except Exception as e:
                print(f"Failed to process {sample_name}: {e}")
                continue

    # --- Mode B: Single BAM Split Processing (Split Mode) ---
    elif args.bam:
        if not args.barcodes:
            print("Error: Must provide -c/--barcodes file when using -b (split mode).")
            sys.exit(1)
        
        print(f"Mode: Splitting single BAM {args.bam} using sinto.")
        
        # 1. Extract merged Chr6 version (reduce size)
        merged_chr6_bam = os.path.join(args.outdir, "merged_chr6.bam")
        if not os.path.exists(merged_chr6_bam):
            run_command(f"samtools view -@ {args.threads} -b '{args.bam}' chr6 > '{merged_chr6_bam}'", "Extracting Chr6 from merged BAM")
            run_command(f"samtools index -@ {args.threads} '{merged_chr6_bam}'")
            
        # 2. Sinto splitting
        print("Running sinto to demultiplex BAM...")
        # sinto will generate SampleName.bam in outdir
        run_command(f"sinto filterbarcodes -b '{merged_chr6_bam}' -c '{args.barcodes}' --outdir '{args.outdir}' -p {args.threads}")
        
        # 3. Iterate over split BAMs and process
        # Find all .bam files in outdir, excluding merged_chr6.bam and intermediate files
        split_bams = glob.glob(os.path.join(args.outdir, "*.bam"))
        
        for sb in split_bams:
            name = os.path.basename(sb)
            # Exclude intermediate files generated by us
            if name == "merged_chr6.bam" or "sorted" in name or "hla_chr6" in name:
                continue
            
            sample_name = name.replace(".bam", "")
            print(f"\n>>> Processing Split Sample: {sample_name} <<<")
            try:
                process_single_bam_for_hla(sb, sample_name, args.outdir, args.arcas, args.threads, args.genes)
            except Exception as e:
                print(f"Failed to process {sample_name}: {e}")

    # --- Final Aggregation ---
    csv_file = os.path.join(args.outdir, "HLA_Genotypes_Summary.csv")
    aggregate_results(args.outdir, gene_list, csv_file)

if __name__ == "__main__":
    main()
